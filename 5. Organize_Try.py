#3-8. Seeing the World
places = ["Tokyo", "Canada", "Singapore", "Sydney", "Paris"]
print("Original: ",places)

#Alphabetical
sl = sorted(places)
print("Alphabetical: ",sl)
print("Original: ",places)

#Reverse-Alphabetical
rsl = sorted(places,reverse=True)
print("Reverse-Alphabetical: ",rsl)
print("Original: ",places)

#Full Reverse
places.reverse()
print("Reverse: ",places)
places.reverse()
print("Reverse back to original: ",places)

#sort()
places.sort()
print("Sorted Alph. permanently: ",places)
places.sort(reverse=True)
print("Reversed Alph. permanently: ",places)

